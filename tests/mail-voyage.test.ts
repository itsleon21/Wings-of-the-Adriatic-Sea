import test from 'node:test';
import assert from 'node:assert/strict';
import {FlightJournal} from '../src/journey/FlightJournal.ts';
import {mooringSites} from '../src/world/Moorings.ts';
const storage=()=>{const values=new Map<string,string>();return {getItem:(key:string)=>values.get(key)??null,setItem:(key:string,value:string)=>{values.set(key,value);}};};
test('mail radio choice redirects guidance, creates one photo, and can be declined',()=>{
 const journal=new FlightJournal(storage()),town=mooringSites.find(s=>s.id==='town')!;
 assert(journal.accept('post','harbor'));
 journal.update(.1,{x:town.berth.x+1700,y:150,z:town.berth.z},true,undefined,130);
 assert.equal(journal.mailProgress?.event,'offered');
 journal.chooseMailEvent(true);
 const target=journal.scenicStop!;
 journal.update(.1,target.position,true,undefined,130,0);
 assert.equal(journal.mailProgress?.event,'completed');
 assert.equal(journal.data.photos,1);
 journal.update(.1,target.position,true,undefined,130,0);
 assert.equal(journal.data.photos,1);
});
test('approach checkpoints survive cancellation and browser reload; return leg unlocks only after delivery',()=>{
 const store=storage(),journal=new FlightJournal(store),town=mooringSites.find(s=>s.id==='town')!;
 assert.equal(journal.accept('return-post','town'),false);
 assert(journal.accept('post','harbor'));
 journal.update(.1,{...town.berth,y:70},true,undefined,120);
 journal.chooseMailEvent(false);journal.cancel();
 const loaded=new FlightJournal(store);
 assert(loaded.accept('post','hotel'));
 assert(loaded.mailApproach);
 loaded.update(.1,town.berth,false,'town',0);
 assert(loaded.data.completed.includes('post'));
 const balance=loaded.workshop.credits;
 loaded.update(.1,town.berth,false,'town',0);
 assert.equal(loaded.workshop.credits,balance);
 assert.equal(loaded.accept('post','harbor'),false);
 assert(loaded.accept('return-post','town'));
 const harbor=mooringSites.find(s=>s.id==='harbor')!;
 loaded.landing(.65,0);loaded.docking(0,0);
 loaded.update(.1,harbor.berth,false,'harbor',0);
 assert(loaded.data.completed.includes('return-post'));
 assert(loaded.workshop.credits>=600);
 assert(loaded.workshop.buy('redwing-0'));
 assert(loaded.workshop.equip('redwing-0'));
});
test('invalid saved mail progress and frozen updates cannot advance tutorial checkpoints',()=>{
 const store=storage();store.setItem('adriatic.journal.v1',JSON.stringify({version:1,mail:{post:{phase:'bogus',event:'accepted'}}}));
 const journal=new FlightJournal(store);
 assert(journal.accept('post','harbor'));
 assert.equal(journal.mailProgress?.phase,'departure');
 const town=mooringSites.find(s=>s.id==='town')!;
 journal.update(0,town.berth,true);
 assert.equal(journal.mailProgress?.phase,'departure');
});
