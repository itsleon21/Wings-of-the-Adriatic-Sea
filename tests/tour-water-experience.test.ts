import test from 'node:test';
import assert from 'node:assert/strict';
import * as T from 'three';
import {FlightJournal} from '../src/journey/FlightJournal.ts';
import {mooringSites} from '../src/world/Moorings.ts';
import {harborRunway} from '../src/world/WorldConfig.ts';
import {Ocean} from '../src/world/Ocean.ts';
import {WaterInteraction} from '../src/world/WaterInteraction.ts';
const journal=()=>{const values=new Map<string,string>();const j=new FlightJournal({getItem:k=>values.get(k)??null,setItem:(k,v)=>{values.set(k,v);}});j.aircraft='m5';return j;};
test('hotel sightseeing offers an optional photo, requires continuous steady flight, and pays once',()=>{
 const j=journal();assert(j.accept('hotel-scenic','hotel'));
 j.update(.1,j.scenicStop!.position,true,undefined,130,0);
 j.update(.1,j.scenicStop!.position,true,undefined,130,0);
 assert.equal(j.tourRequest,'offered');j.chooseTourRequest(true);
 const target=j.tourPhotoTarget.position;
 for(let i=0;i<15;i++)j.update(.1,target,true,undefined,130,0);
 assert(j.tourPhotoSeconds>1);
 j.update(.1,target,true,undefined,130,.4);
 assert.equal(j.tourPhotoSeconds,0);
 j.update(0,target,true,undefined,130,0);assert.equal(j.tourPhotoSeconds,0);
 for(let i=0;i<30;i++)j.update(.1,target,true,undefined,130,0);
 assert.equal(j.tourRequest,'completed');assert.equal(j.data.photos,1);
 if(j.scenicStop)j.update(.1,j.scenicStop.position,true,undefined,130,0);
 const berth=mooringSites.find(s=>s.id==='hotel')!.berth;
 j.update(.1,berth,false,'hotel',0);
 assert.equal(j.active,undefined);const credits=j.workshop.credits;
 j.update(.1,berth,false,'hotel',0);assert.equal(j.workshop.credits,credits);
});
test('passenger photo can be abandoned without blocking the original route',()=>{
 const j=journal();assert(j.accept('hotel-scenic','hotel'));
 j.update(.1,j.scenicStop!.position,true,undefined,130,0);
 j.update(.1,{x:0,y:100,z:0},true,undefined,130,0);
 j.chooseTourRequest(true);j.chooseTourRequest(false);
 assert.equal(j.tourRequest,'declined');
 j.update(.1,j.scenicStop!.position,true,undefined,130,0);
 j.update(.1,mooringSites.find(s=>s.id==='hotel')!.berth,false,'hotel',0);
 assert.equal(j.active,undefined);assert.equal(j.data.photos,0);
});
test('liftoff drips continue briefly, freeze on pause and clear completely on reset',()=>{
 const sea=new Ocean(),fx=new WaterInteraction(sea),p=new T.Vector3(harborRunway.x,2,harborRunway.z);
 fx.update(1/60,p,0,20,true,0,'m5');
 const drops=fx.root.children.find(o=>o.name==='Hull and float spray / gravity particles') as T.Points;
 const active=()=>Array.from(drops.geometry.attributes.opacity.array).filter(v=>v>0).length;
 const initial=active();p.y=3;
 for(let i=0;i<20;i++)fx.update(1/60,p,0,20,false,0,'m5');
 assert(active()>initial);
 const before=Array.from(drops.geometry.attributes.position.array);
 fx.update(0,p,0,20,false,0,'m5');assert.deepEqual(Array.from(drops.geometry.attributes.position.array),before);
 for(let i=0;i<180;i++)fx.update(1/60,p,0,20,false,0,'m5');
 assert.equal(active(),0);fx.reset();assert.equal(active(),0);sea.dispose();
});
